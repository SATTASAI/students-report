// อายุเป็นเดือน (มีเศษ) ณ วันที่วัด
export function ageMonths(birthIso, atIso) {
  if (!birthIso || !atIso) return null;
  const b = new Date(`${String(birthIso).slice(0, 10)}T00:00:00Z`), a = new Date(`${String(atIso).slice(0, 10)}T00:00:00Z`);
  if (Number.isNaN(b.getTime()) || Number.isNaN(a.getTime()) || a < b) return null;
  return (a - b) / 86400000 / 30.4375;
}

// เพศจากข้อมูลทะเบียน ถ้าไม่มีดูจากคำนำหน้าชื่อ
export function sexOf(student) {
  if (student?.gender === "ช" || student?.gender === "ญ") return student.gender;
  const n = String(student?.name || student?.name_prefix || "");
  return /^(เด็กชาย|ด\.ช\.|นาย)/.test(n) ? "ช" : /^(เด็กหญิง|ด\.ญ\.|นางสาว|น\.ส\.)/.test(n) ? "ญ" : null;
}

function lmsAt(sex, months) {
  const t = WHO_BMI_LMS[sex];
  if (!t || months == null || months < t[0][0] || months > t[t.length - 1][0]) return null;
  const i = Math.min(t.length - 2, Math.floor(months) - t[0][0]), [m0, L0, M0, S0] = t[i], [, L1, M1, S1] = t[i + 1], f = months - m0;
  return { L: L0 + (L1 - L0) * f, M: M0 + (M1 - M0) * f, S: S0 + (S1 - S0) * f };
}

// ค่า z ของ BMI ตามอายุ (วิธีของ WHO รวมการปรับส่วนที่เกิน ±3 SD)
export function bmiZ(bmi, sex, months) {
  const p = lmsAt(sex, months);
  if (!p || !(bmi > 0)) return null;
  const { L, M, S } = p, sd = (k) => M * (1 + L * S * k) ** (1 / L);
  let z = ((bmi / M) ** L - 1) / (L * S);
  if (z > 3) z = 3 + (bmi - sd(3)) / (sd(3) - sd(2));
  else if (z < -3) z = -3 + (bmi - sd(-3)) / (sd(-2) - sd(-3));
  return z;
}

// เกณฑ์ WHO: ต่ำกว่า 5 ปี >+1 เสี่ยง, >+2 น้ำหนักเกิน, >+3 อ้วน · 5 ปีขึ้นไป >+1 น้ำหนักเกิน, >+2 อ้วน · <-2 ผอม, <-3 ผอมมาก
export function bmiStatus(z, months) {
  if (z == null) return null;
  if (z < -3) return "ผอมมาก";
  if (z < -2) return "ผอม";
  if (months < 60) return z > 3 ? "อ้วน" : z > 2 ? "น้ำหนักเกิน" : z > 1 ? "เสี่ยงน้ำหนักเกิน" : "สมส่วน";
  return z > 2 ? "อ้วน" : z > 1 ? "น้ำหนักเกิน" : "สมส่วน";
}

// วิเคราะห์ 1 ครั้งการวัด → {bmi, months, z, status} (ค่า null ถ้าข้อมูลไม่พอ)
export function analyzeBody(student, rec, atIso) {
  const bmi = bmiOf(Number(rec?.weight), Number(rec?.height));
  if (bmi == null) return null;
  const months = ageMonths(student?.birth_date, atIso), sex = sexOf(student);
  const z = bmiZ(bmi, sex, months);
  return { bmi, months, sex, z, status: bmiStatus(z, months), why: z != null ? null : !student?.birth_date ? "ไม่มีวันเกิด" : !sex ? "ไม่ทราบเพศ" : "อายุนอกช่วง 2–15 ปี" };
}

export const ageText = (months) => (months == null ? "" : `${Math.floor(months / 12)} ปี ${Math.floor(months % 12)} เดือน`);
